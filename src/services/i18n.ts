export const currentLanguageState = {
  lang: 'en' as Language,
  listeners: [] as ((lang: Language) => void)[],
  
  setLang(l: Language) {
    this.lang = l;
    this.listeners.forEach(fn => fn(l));
  },

  subscribe(fn: (lang: Language) => void) {
    this.listeners.push(fn);
    return () => {
      this.listeners = this.listeners.filter(l => l !== fn);
    };
  },

  t(key: keyof typeof translations.en): string {
    const dict = (translations as any)[this.lang] || translations.en;
    return dict[key] || (translations.en as any)[key] || key;
  }
};
